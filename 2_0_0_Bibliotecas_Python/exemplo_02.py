import math

# Definindo valores
numero = 25
potencia = 3

# Raiz quadrada
raiz = math.sqrt(numero)

# Potência
resultado = math.pow(numero, potencia)

# Fatorial
fatorial = math.factorial(5)

# Arredondamento para cima
arredondar_cima = math.ceil(8.3)

# Arredondamento para baixo
arredondar_baixo = math.floor(8.9)

# Exibindo resultados

print("Raiz quadrada:", raiz)
print("Potência:", resultado)
print("Fatorial:", fatorial)
print("Arredondamento para cima:", arredondar_cima)
print("Arredondamento para baixo:", arredondar_baixo)